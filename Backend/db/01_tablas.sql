-- -------------------------------------------------------------
--  CATEGORIA: las 6 categorías del formulario y del filtro
-- -------------------------------------------------------------
CREATE TABLE categoria (
  id      NUMBER(5)     NOT NULL,
  nombre  VARCHAR2(30)  NOT NULL,
  CONSTRAINT pk_categoria        PRIMARY KEY (id),
  CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);

CREATE SEQUENCE seq_categoria START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER trg_categoria_id
BEFORE INSERT ON categoria
FOR EACH ROW
WHEN (NEW.id IS NULL)
BEGIN
  SELECT seq_categoria.NEXTVAL INTO :NEW.id FROM dual;
END;
/

-- -------------------------------------------------------------
--  PRODUCTO (HU1 registrar, HU2 modificar, HU3 consultar,
--            HU4 inactivar / activar)
-- -------------------------------------------------------------
CREATE TABLE producto (
  id            NUMBER(10)      NOT NULL,
  ref           VARCHAR2(20)    NOT NULL,
  nombre        VARCHAR2(120)   NOT NULL,
  precio        NUMBER(12)      NOT NULL,
  categoria_id  NUMBER(5)       NOT NULL,
  stock         NUMBER(8)       NOT NULL,
  descripcion   VARCHAR2(1000)  NOT NULL,
  -- La foto NO se guarda en la base ni en el backend: está en el bucket
  -- "eden-fotos" de Oracle Cloud (Object Storage). Aquí solo va su nombre
  -- dentro del bucket, por ejemplo 'productos/AnillosAzules.jpg'.
  imagen        VARCHAR2(300)   NOT NULL,
  estado        VARCHAR2(8)     DEFAULT 'Activo' NOT NULL,
  CONSTRAINT pk_producto          PRIMARY KEY (id),
  CONSTRAINT uq_producto_ref      UNIQUE (ref),
  CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
  CONSTRAINT ck_producto_precio   CHECK (precio > 0),
  CONSTRAINT ck_producto_stock    CHECK (stock >= 0),
  -- Oracle no tiene tipo ENUM: el CHECK (más el NOT NULL de la columna)
  -- limita el estado a una lista fija de valores
  CONSTRAINT ck_producto_estado   CHECK (estado IN ('Activo', 'Inactivo'))
);

CREATE SEQUENCE seq_producto START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER trg_producto_id
BEFORE INSERT ON producto
FOR EACH ROW
WHEN (NEW.id IS NULL)
BEGIN
  SELECT seq_producto.NEXTVAL INTO :NEW.id FROM dual;
END;
/

-- Regla del negocio: un producto sin unidades no puede quedar activo
-- (HU4, escenario 3 y HU2 cuando el stock queda en 0)
CREATE OR REPLACE TRIGGER trg_producto_sin_stock
BEFORE INSERT OR UPDATE ON producto
FOR EACH ROW
BEGIN
  IF :NEW.stock <= 0 THEN
    :NEW.estado := 'Inactivo';
  END IF;
END;
/

-- -------------------------------------------------------------
--  USUARIO (Sprint 2: registro, inicio de sesión y ajustes de cuenta)
-- -------------------------------------------------------------
CREATE TABLE usuario (
  id             NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR2(100)  NOT NULL,
  identificacion VARCHAR2(30)   NOT NULL,
  telefono       VARCHAR2(20)   NOT NULL,
  correo         VARCHAR2(150)  NOT NULL,
  usuario        VARCHAR2(50)   NOT NULL,
  direccion      VARCHAR2(300)  NOT NULL,
  -- La contraseña nunca se guarda: solo su hash.
  password_hash  VARCHAR2(255)  NOT NULL,
  rol            VARCHAR2(20)   DEFAULT 'cliente' NOT NULL,
  estado         VARCHAR2(10)   DEFAULT 'Activo' NOT NULL,
  CONSTRAINT uq_usuario_correo UNIQUE (correo),
  CONSTRAINT uq_usuario_nombre UNIQUE (usuario),
  CONSTRAINT uq_usuario_identificacion UNIQUE (identificacion),
  -- Igual que en PRODUCTO: Oracle no tiene ENUM, el CHECK limita los valores
  CONSTRAINT ck_usuario_rol    CHECK (rol IN ('cliente', 'admin')),
  CONSTRAINT ck_usuario_estado CHECK (estado IN ('Activo', 'Inactivo'))
);

CREATE UNIQUE INDEX uq_usuario_nombre_ci ON usuario (LOWER(usuario));
CREATE UNIQUE INDEX uq_usuario_correo_ci ON usuario (LOWER(correo));
